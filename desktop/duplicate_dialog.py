"""Compact confirmation for deliberate duplicate playlist membership."""
from math import ceil

from PySide6.QtCore import Qt
from PySide6.QtGui import QTextCursor, QTextListFormat, QTextOption
from PySide6.QtWidgets import (QDialog, QDialogButtonBox, QFrame, QLabel,
                              QTextEdit, QVBoxLayout, QWidget)


class DuplicateAddDialog(QDialog):
    def __init__(self, playlist: str, titles: list[str], count: int, parent=None):
        super().__init__(parent)
        self.setWindowTitle('Already in playlist')
        self.setModal(True)
        available=self.screen().availableGeometry().width()
        width=min(480,max(320,available-48))
        self.setFixedWidth(width)
        layout=QVBoxLayout(self)
        layout.setContentsMargins(24,22,24,20)
        layout.setSpacing(12)

        heading=QLabel('Already in playlist')
        heading.setStyleSheet('font-size: 16px; font-weight: 600;')
        layout.addWidget(heading)
        self.playlist=QTextEdit()
        self.playlist.setReadOnly(True)
        self.playlist.setAcceptRichText(False)
        self.playlist.setFrameShape(QFrame.NoFrame)
        self.playlist.setFocusPolicy(Qt.NoFocus)
        self.playlist.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.playlist.setWordWrapMode(QTextOption.WrapAtWordBoundaryOrAnywhere)
        self.playlist.setStyleSheet('font-size: 13px; font-weight: 600; border: none; padding: 0;')
        self.playlist.setAccessibleName('Playlist')
        self.playlist.setPlainText(f'“{playlist}”')
        self.playlist.setFixedWidth(width-48)
        self.playlist.document().setDocumentMargin(0)
        self.playlist.ensurePolished()
        self.playlist.document().setTextWidth(self.playlist.width()-16)
        self.playlist.setFixedHeight(min(80,max(20,ceil(self.playlist.document().size().height())+4)))
        layout.addWidget(self.playlist)

        panel=QWidget()
        panel.setObjectName('TrackDetails')
        body=QVBoxLayout(panel)
        body.setContentsMargins(12,10,12,10)
        body.setSpacing(8)
        self.tracks=QTextEdit()
        self.tracks.setReadOnly(True)
        self.tracks.setAcceptRichText(False)
        self.tracks.setFrameShape(QFrame.NoFrame)
        self.tracks.setFocusPolicy(Qt.NoFocus)
        self.tracks.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
        self.tracks.setWordWrapMode(QTextOption.WrapAtWordBoundaryOrAnywhere)
        self.tracks.setStyleSheet('font-size: 13px; border: none; padding: 0;')
        self.tracks.setAccessibleName('Tracks already in playlist')
        self.tracks.setPlainText('\n'.join(titles[:6]))
        self.tracks.document().setDocumentMargin(0)
        self.tracks.document().setIndentWidth(14)
        cursor=QTextCursor(self.tracks.document())
        cursor.select(QTextCursor.Document)
        bullets=QTextListFormat()
        bullets.setStyle(QTextListFormat.ListDisc)
        bullets.setIndent(1)
        cursor.createList(bullets)
        self.tracks.setFixedWidth(width-48-24)
        self.tracks.ensurePolished()
        self.tracks.document().setTextWidth(self.tracks.width()-16)
        self.tracks.setFixedHeight(min(200,max(28,ceil(self.tracks.document().size().height())+4)))
        body.addWidget(self.tracks)
        self.more=QLabel(f'…and {count-6} more' if count>6 else '')
        self.more.setObjectName('SettingsSub')
        self.more.setVisible(count>6)
        body.addWidget(self.more)
        layout.addWidget(panel)

        self.question=QLabel(f"Add {'this track' if count==1 else 'these tracks'} again?")
        self.question.setTextFormat(Qt.PlainText)
        layout.addWidget(self.question)
        layout.addSpacing(4)
        self.buttons=QDialogButtonBox()
        self.add=self.buttons.addButton('Add Anyway',QDialogButtonBox.AcceptRole)
        self.skip=self.buttons.addButton('Skip',QDialogButtonBox.RejectRole)
        for button in (self.add,self.skip):
            button.setMinimumWidth(104)
            button.setFixedHeight(32)
        self.add.setAutoDefault(False)
        self.skip.setObjectName('Primary')
        self.skip.setDefault(True)
        self.skip.setFocus()
        self.buttons.accepted.connect(self.accept)
        self.buttons.rejected.connect(self.reject)
        layout.addWidget(self.buttons)
