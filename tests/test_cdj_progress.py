class CdjMeasuredProgress(unittest.TestCase):
    def setUp(self):
        self.fixture=fixtures.CdjTransactionTests();self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        self.audio=b'captured generated bytes'*(140000)
        (self.fixture.candidate/'Contents/Artist/track.wav').write_bytes(self.audio)
        self.plan=self.fixture.plan();self.addCleanup(self.plan.close)
        self.events=[];self.files=[];self.stop=Event()

    def run_commit(self,callback=None):
        def progress(stage,done,total,label):
            self.events.append((stage,done,total,label))
            if callback is not None:callback(stage,done,total,label)
        with operation_scope(self.stop,progress):
            return tx.commit(self.plan,should_cancel=self.stop.is_set,
                             on_progress=lambda *args:self.files.append(args))

    def test_checks_report_before_first_device_write_and_copy_reports_actual_bytes(self):
        actual=tx.CdjSession.atomic_write;writes=[]
        def write(session,path,raw):
            if not writes:
                checks=[row for row in self.events if row[0]=='CDJ checking']
                self.assertEqual(checks[0][1:3],(0,len(self.plan.changes)))
                self.assertEqual(checks[-1][1:3],(len(self.plan.changes),len(self.plan.changes)))
                self.assertEqual(self.files,[])
            writes.append(path);return actual(session,path,raw)
        clock=itertools.count()
        with mock.patch.object(tx.CdjSession,'atomic_write',write), \
                mock.patch.object(tx.time,'monotonic',side_effect=lambda:next(clock)):
            self.run_commit()
        label='Contents/Artist/track.wav'
        copies=[row for row in self.events if row[0]=='CDJ copying' and row[3]==label]
        self.assertEqual(copies[0][1:3],(0,len(self.audio)))
        self.assertEqual(copies[-1][1:3],(len(self.audio),len(self.audio)))
        self.assertTrue(any(0<done<len(self.audio) for _,done,_,_ in copies))
        self.assertEqual([row[1] for row in copies],sorted(row[1] for row in copies))
        self.assertEqual((self.fixture.target/label).read_bytes(),self.audio)
        self.assertEqual([row[2] for row in self.files],[row.path for row in self.plan.changes])
        self.assertEqual(self.events[-1][:3],('CDJ finished',1,1))
        self.assertFalse((self.fixture.target/tx.JOURNAL).exists())

    def test_preflight_cancellation_creates_no_journal_or_publication(self):
        def cancel(stage,_done,_total,_label):
            if stage=='CDJ checking':self.stop.set()
        with self.assertRaises(OperationCancelled):self.run_commit(cancel)
        self.fixture.assert_old_generation()
        self.assertEqual(self.files,[])
        self.assertFalse(any(row[0]=='CDJ copying' for row in self.events))

    def test_mid_copy_cancellation_rolls_back_before_legacy_file_acknowledgement(self):
        def cancel(stage,done,total,label):
            if stage=='CDJ copying' and label.startswith('Contents/') and 0<done<total:
                self.stop.set()
        clock=itertools.count()
        with mock.patch.object(tx.time,'monotonic',side_effect=lambda:next(clock)):
            with self.assertRaises(OperationCancelled) as caught:self.run_commit(cancel)
        self.assertEqual(caught.exception.recovery_status,'rolled back')
        self.fixture.assert_old_generation()
        self.assertEqual(self.files,[])
        self.assertFalse(any(row[0]=='CDJ finished' for row in self.events))
        self.assertFalse(list(self.fixture.target.rglob('*.sbpart')))

    def test_legacy_callback_still_follows_complete_file_publication(self):
        calls=[]
        def completed(done,total,label):
            calls.append((done,total,label))
            self.assertEqual((self.fixture.target/label).read_bytes(),self.audio)
            self.stop.set()
        with operation_scope(self.stop,lambda *args:self.events.append(args)):
            with self.assertRaises(OperationCancelled):
                tx.commit(self.plan,should_cancel=self.stop.is_set,on_progress=completed)
        self.assertEqual(calls,[(1,len(self.plan.changes),'Contents/Artist/track.wav')])
        self.fixture.assert_old_generation(reusable=True)

    def test_one_operation_metric_log_accounts_for_real_publications_and_stage_times(self):
        with mock.patch('soundbox.operation_control.logging.getLogger') as logger:
            self.run_commit()
        logger.return_value.info.assert_called_once()
        metrics=logger.return_value.info.call_args.args[1]
        self.assertEqual(metrics['cdj_published_bytes'],
                         sum(change.size for change in self.plan.changes if change.new_sha256))
        for key in ('cdj_preflight_elapsed_ns','cdj_copy_elapsed_ns','cdj_cleanup_elapsed_ns'):
            self.assertGreater(metrics[key],0)
            self.assertLessEqual(metrics[key],metrics['cdj_commit_elapsed_ns'])

    def test_cancelled_temporary_copy_records_time_without_claiming_published_bytes(self):
        def cancel(stage,done,total,label):
            if stage=='CDJ copying' and label.startswith('Contents/') and 0<done<total:
                self.stop.set()
        clock=itertools.count()
        with mock.patch.object(tx.time,'monotonic',side_effect=lambda:next(clock)), \
                mock.patch('soundbox.operation_control.logging.getLogger') as logger:
            with self.assertRaises(OperationCancelled):self.run_commit(cancel)
        logger.return_value.info.assert_called_once()
        metrics=logger.return_value.info.call_args.args[1]
        self.assertEqual(metrics.get('cdj_published_bytes',0),0)
        self.assertGreater(metrics['cdj_copy_elapsed_ns'],0)
        self.assertGreaterEqual(metrics['cdj_commit_elapsed_ns'],metrics['cdj_copy_elapsed_ns'])
        self.fixture.assert_old_generation()


class CdjProgressPresentation(unittest.TestCase):
    @classmethod
    def setUpClass(cls):cls.app=QApplication.instance() or QApplication([])

    def setUp(self):
        self.worker=object()
        self.host=SimpleNamespace(_cdj_worker=self.worker,_shutting_down=False,_cancelling=False,
            _set_device_progress=mock.Mock(),_start_pulse=mock.Mock(),_set_status_count=mock.Mock(),
            status_label=mock.Mock())
        self.state={'value':650,'published':0,'publication_total':2,
                    'weights':(1,1),'prefix':(0,1,2)}

    def tick(self,stage,done,total,label=''):
        _cdj_progress(self.host,self.worker,self.state,stage,done,total,label)

    def test_measured_phases_and_file_bytes_are_monotonic_and_never_terminal(self):
        for event in (('CDJ checking',0,707,''),('CDJ checking',350,707,''),
                ('CDJ checking',707,707,''),('CDJ saving',0,1,''),
                ('CDJ publishing',0,2,''),('CDJ copying',0,4_000_000,'Contents/Artist/A song.wav'),
                ('CDJ copying',2_000_000,4_000_000,'Contents/Artist/A song.wav'),
                ('CDJ copying',4_000_000,4_000_000,'Contents/Artist/A song.wav'),
                ('CDJ publishing',1,2,''),('CDJ publishing',2,2,''),
                ('CDJ finalizing',0,1,''),('CDJ cleanup',0,0,''),('CDJ finished',1,1,'')):
            self.tick(*event)
        values=[call.args[0] for call in self.host._set_device_progress.call_args_list]
        self.assertEqual(values,sorted(values));self.assertEqual(values[0],650)
        self.assertEqual(values[-1],990);self.assertNotIn(1000,values)
        self.assertIn(mock.call('Copying A song.wav',keep_count=True),self.host._start_pulse.call_args_list)
        self.assertIn(mock.call(2_000_000,4_000_000,byte_counts=True),self.host._set_status_count.call_args_list)
        self.assertIn(mock.call(350,707,byte_counts=False),self.host._set_status_count.call_args_list)

    def test_stale_cancelled_and_shutdown_workers_cannot_repaint(self):
        for attr,value in (('_cdj_worker',object()),('_cancelling',True),('_shutting_down',True)):
            previous=getattr(self.host,attr);setattr(self.host,attr,value)
            self.tick('CDJ copying',5,10,'Contents/song.wav')
            self.host._set_device_progress.assert_not_called();self.host._start_pulse.assert_not_called()
            setattr(self.host,attr,previous)

    def test_worker_scope_delivers_large_byte_values_and_cooperative_cancellation(self):
        def operation(_cancel,_progress):
            phase_progress('CDJ copying',2**32+1,2**32+2,'Contents/large.wav')
            checkpoint();return 'complete'
        worker=CdjWorker(operation);self.addCleanup(worker.deleteLater);events=[]
        worker.detail_progress.connect(lambda *args:events.append(args),Qt.DirectConnection)
        worker.run();self.assertEqual(worker.result,'complete')
        self.assertEqual(events,[('CDJ copying',2**32+1,2**32+2,'Contents/large.wav')])
        worker.cancel();worker.run();self.assertIsInstance(worker.result,OperationCancelled)

    def test_actual_review_callbacks_keep_bar_monotonic_and_close_only_after_commit(self):
        values=[];started=[]
        host=SimpleNamespace(_shutting_down=False,_cancelling=False,_cdj_worker=None,
            _set_device_progress=lambda value:values.append(value),_start_pulse=mock.Mock(),
            _set_status_count=mock.Mock(),status_label=mock.Mock(),_finish_cdj=mock.Mock(),
            _finish_device_result_worker=mock.Mock(),
            _start_device_worker=lambda worker,*_args:started.append(worker))
        plan=SimpleNamespace(changes=[object(),object()],requires_commit=True,
                             overwritten_playlists=(),close=mock.Mock())
        def commit(_plan,*,should_cancel,on_progress):
            phase_progress('CDJ checking',1,2,'')
            phase_progress('CDJ checking',2,2,'')
            phase_progress('CDJ publishing',0,2,'Contents/song.wav')
            phase_progress('CDJ copying',50,100,'Contents/song.wav')
            on_progress(1,2,'Contents/song.wav')
            phase_progress('CDJ finalizing',0,1,'')
            phase_progress('CDJ cleanup',0,0,'')
            phase_progress('CDJ finished',1,1,'')
            return {'saved':True}
        with mock.patch.object(tx,'commit',side_effect=commit):
            CdjDeviceMixin._review_cdj_plan(host,'/generated/no-device-io',plan)
            worker=started[0];self.addCleanup(worker.deleteLater)
            plan.close.assert_not_called();worker.run();plan.close.assert_called_once()
        self.assertEqual(values,sorted(values));self.assertEqual(values[-1],990)
        self.assertNotIn(1000,values);host._finish_cdj.assert_not_called()

    def test_only_successful_finished_delivery_marks_terminal_progress(self):
        from desktop.devices import DeviceFacts
        from desktop.usb_device_view import UsbSnapshot
        dev='/generated/no-device-io'
        for result in ({'saved':True},RuntimeError('Generated failure')):
            with self.subTest(success=not isinstance(result,Exception)):
                host=SimpleNamespace(_export_batch=None,_exporting=True,_cancelling=False,
                    _stop_pulse=mock.Mock(),cancel_btn=mock.Mock(),progress=mock.Mock(),
                    _sync_cue_editing=mock.Mock(),_flash_status=mock.Mock(),
                    _update_device_action_state=mock.Mock(),_current_device_path='',
                    _usb_view_cache={dev:UsbSnapshot(Path(dev),7,DeviceFacts())},
                    _usb_view_requests={dev},_device_mount_tokens={dev:7},_device_profiles={})
                with mock.patch('desktop.cdj.QMessageBox.warning'), \
                        mock.patch('desktop.cdj.device_facts',side_effect=AssertionError('Completion device read')):
                    CdjDeviceMixin._finish_cdj(host,dev,result)
                if isinstance(result,Exception):host.progress.setValue.assert_not_called()
                else:host.progress.setValue.assert_called_once_with(1000)
                host.progress.setVisible.assert_called_once_with(False)

    def test_actual_review_weights_large_media_and_tiny_metadata_by_captured_bytes(self):
        values=[];started=[]
        host=SimpleNamespace(_shutting_down=False,_cancelling=False,_cdj_worker=None,
            _set_device_progress=lambda value:values.append(value),_start_pulse=mock.Mock(),
            _set_status_count=mock.Mock(),status_label=mock.Mock(),_finish_cdj=mock.Mock(),
            _finish_device_result_worker=mock.Mock(),
            _start_device_worker=lambda worker,*_args:started.append(worker))
        big=8*1024*1024
        plan=SimpleNamespace(changes=[SimpleNamespace(size=big),
            *(SimpleNamespace(size=1024) for _ in range(100))],requires_commit=True,
            overwritten_playlists=(),close=mock.Mock())
        def commit(_plan,*,should_cancel,on_progress):
            phase_progress('CDJ checking',101,101,'')
            phase_progress('CDJ publishing',0,101,'Contents/song.wav')
            phase_progress('CDJ copying',big//2,big,'Contents/song.wav')
            self.assertGreaterEqual(values[-1],850);self.assertLessEqual(values[-1],865)
            phase_progress('CDJ copying',big,big,'Contents/song.wav')
            after_media=values[-1];self.assertGreater(after_media,960)
            on_progress(1,101,'Contents/song.wav')
            self.assertEqual(values[-1],after_media)
            for index in range(1,101):
                phase_progress('CDJ publishing',index,101,'PIONEER/generated.DAT')
                on_progress(index+1,101,'PIONEER/generated.DAT')
            return {'saved':True}
        with mock.patch.object(tx,'commit',side_effect=commit):
            CdjDeviceMixin._review_cdj_plan(host,'/generated/no-device-io',plan)
            worker=started[0];self.addCleanup(worker.deleteLater);worker.run()
        self.assertNotIsInstance(worker.result,Exception)
        self.assertEqual(values,sorted(values));self.assertEqual(values[-1],970)
        self.assertNotIn(1000,values)
