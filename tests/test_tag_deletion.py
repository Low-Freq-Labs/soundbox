class DeleteAdmission(unittest.TestCase):
    def test_creation_and_assignment_acceptance_never_enable_deletion(self):
        with tempfile.TemporaryDirectory() as area:
            path = Path(area) / 'authority.json'
            source = Path(area).resolve() / 'source/master.db'
            source.parent.mkdir()
            source.write_bytes(b'No disabled gate may open these generated bytes')
            create = definitions.TagDefinitionAuthority(str(source), 'library', 'a' * 64,
                accepted=True, protocol_profile=definitions.NATIVE_CREATE_PROFILE.profile)
            path.write_text(json.dumps(asdict(create)))
            self.assertIsNone(definitions.load_deletion_authority(path, source, 'library'))
            deletion = definitions.TagDeletionAuthority(str(source), 'library', 'a' * 64,
                accepted=True, protocol_profile=definitions.NATIVE_CREATE_PROFILE.profile)
            path.write_text(json.dumps(asdict(deletion)))
            self.assertIsNone(definitions.load_deletion_authority(path, source, 'library'))
            unaccepted = replace(deletion, accepted=False, protocol_profile=definitions.NATIVE_DELETE_PROFILE.profile)
            path.write_text(json.dumps(asdict(unaccepted)))
            self.assertIsNone(definitions.load_deletion_authority(path, source, 'library'))
            with self.assertRaises(WriteProofError):
                definitions.TagDeletionStore(create, Path(area).resolve() / 'recovery')
            store = definitions.TagDeletionStore(deletion, Path(area).resolve() / 'recovery')
            with mock.patch.object(store.lease, '_connect') as connect:
                with self.assertRaises(WriteProofError):
                    store.check_ready()
                with self.assertRaises(WriteProofError):
                    store.recover()
                request = definitions.deletion_request_for('library', '1', '1', TAG.tag_id, TAG.source_uuid, TAG.name)
                with self.assertRaises(WriteProofError):
                    store.apply(request)
                connect.assert_not_called()

    def test_request_captures_existing_opaque_identity_and_freezes_clock(self):
        request = definitions.deletion_request_for('library', '1', '1', TAG.tag_id,
            TAG.source_uuid, TAG.name, now=datetime(2026, 11, 12, 12, 0, tzinfo=timezone.utc))
        self.assertEqual(request['timestamp'], '2026-11-12 12:00:00.000 +00:00')
        self.assertEqual(definitions.validate_deletion_request(deepcopy(request)), request)
        for change in ({'action': 'create'}, {'tag_id': '01'}, {'tag_id': True}, {'tag_uuid': ''},
                       {'category_uuid': ''}, {'name': ' renamed '}, {'operation_id': '../escape'},
                       {'timestamp': '2026-11-12 12:00:00 +00:00'}, {'final_timestamp': 'extra'}):
            with self.subTest(change=change), self.assertRaises(WriteProofError):
                definitions.validate_deletion_request({**request, **change})
        with self.assertRaises(WriteProofError):
            definitions.deletion_request_for('library', '1', '1', TAG.tag_id, TAG.source_uuid,
                                             TAG.name, now=datetime(2026, 11, 12))

    def test_independent_native_phase_clocks_survive_json_without_forcing_time_order(self):
        now = datetime(2026, 11, 13, 3, 2, 8, 181000, tzinfo=timezone.utc)
        request = definitions.deletion_request_for('library', '1', '1', TAG.tag_id, TAG.source_uuid, TAG.name,
            now=now, target_now=now, sibling_now=now + timedelta(milliseconds=26),
            association_now=now - timedelta(milliseconds=98))
        self.assertEqual(request['clocks'], dict(target='2026-11-13 03:02:08.181 +00:00',
            siblings='2026-11-13 03:02:08.207 +00:00', associations='2026-11-13 03:02:08.083 +00:00'))
        self.assertEqual(definitions.validate_deletion_request(json.loads(json.dumps(request))), request)
        legacy = {key: value for key, value in request.items() if key != 'clocks'}
        self.assertEqual(definitions.validate_deletion_request(legacy), legacy)
        for clocks in ({}, {**request['clocks'], 'extra': request['timestamp']},
                       {**request['clocks'], 'target': True}):
            with self.subTest(clocks=clocks), self.assertRaises(WriteProofError):
                definitions.validate_deletion_request({**request, 'clocks': clocks})

    def test_effects_count_active_dto_memberships_and_signed_tag_conditions_without_mutating_rules(self):
        lib = library()
        lib.tracks_by_id['song'] = Track('song', 'Song', '', 'file:///synthetic.wav', source_tag_ids=[TAG.tag_id])
        rule = smart_tag_rule('123', [TAG.tag_id])
        lib.source_playlist_catalog['nodes'] = [dict(ID='123', Name='Smart', Attribute=4,
            rb_local_deleted=0, SmartList=rule)]
        before = deepcopy(lib)
        self.assertEqual(tag_deletion_effects(lib, TAG), (1, ('Smart',), False))
        self.assertEqual(lib, before)
        lib.source_playlist_catalog['nodes'][0]['rb_local_deleted'] = 1
        self.assertEqual(tag_deletion_effects(lib, TAG), (1, (), False))

    def test_native_aliases_are_counted_once_and_unregistered_tracks_have_no_source_assignment(self):
        lib = library()
        first = Track('native', 'Song', '', 'file:///synthetic.wav', source_tag_ids=[TAG.tag_id])
        alias = replace(first, track_id='logical', source_native_id='native')
        unavailable = Track('unregistered', 'Import', '', 'file:///other.wav')
        lib.tracks_by_id = {track.track_id: track for track in (first, alias, unavailable)}
        self.assertEqual(tag_deletion_effects(lib, TAG), (1, (), False))

    def test_negative_and_any_references_are_counted_but_different_tags_are_omitted(self):
        lib = library()
        rule = smart_tag_rule('123', [TAG.tag_id, '42']).replace('Operator="8"', 'Operator="9"')
        lib.source_playlist_catalog['nodes'] = [dict(ID='123', Name='Not tag', Attribute=4,
            rb_local_deleted=0, SmartList=rule)]
        self.assertEqual(tag_deletion_effects(lib, TAG), (0, ('Not tag',), False))
        lib.source_playlist_catalog['nodes'][0]['SmartList'] = smart_tag_rule('123', ['42'])
        self.assertEqual(tag_deletion_effects(lib, TAG), (0, (), False))

    def test_missing_or_malformed_rules_remain_unknown_and_blank_constructor_is_safe(self):
        lib = library()
        lib.source_playlist_catalog = {}
        self.assertEqual(tag_deletion_effects(lib, TAG), (0, (), True))
        for rule in ('<broken', '', '<NODE><CONDITION PropertyName="myTag" ValueLeft="bogus"/></NODE>'):
            lib.source_playlist_catalog = dict(nodes=[dict(ID='123', Attribute=4, rb_local_deleted=0, SmartList=rule)])
            self.assertEqual(tag_deletion_effects(lib, TAG), (0, (), True))
        lib.source_playlist_catalog['nodes'][0]['SmartList'] = None
        self.assertEqual(tag_deletion_effects(lib, TAG), (0, (), False))


class DeleteController(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.app = QApplication.instance() or QApplication([])

    def setUp(self):
        area = self.enterContext(tempfile.TemporaryDirectory())
        self.window = Window(Path(area))
        self.addCleanup(self.window.deleteLater)
        self.window.lib = library()
        self.enterContext(mock.patch('desktop.tag_creation_controller.assert_rekordbox_closed'))
        self.applied = []
        owner = self
        class Store:
            def apply(self, request):
                owner.applied.append(deepcopy(request))
                return dict(ID=request['tag_id'])
        self.controller = TagDefinitionController(self.window, store_factory=lambda _: Store(),
            deletion_store_factory=lambda _: Store(), loader=lambda _: replace(self.window.lib, source_tags=[]))
        self.addCleanup(self.controller.stop)
        self.request = definitions.deletion_request_for('library', '1', '1', TAG.tag_id, TAG.source_uuid, TAG.name)

    def test_create_factory_does_not_bypass_separate_deletion_authority(self):
        controller = TagDefinitionController(self.window, store_factory=lambda _: object(), loader=lambda _: None)
        self.addCleanup(controller.stop)
        self.assertEqual(controller.deletion_reason(), 'Deleting tags is not enabled for this library yet')
        self.assertFalse(controller.enqueue_deletion(self.request))
        self.assertFalse(self.window.saved)
        self.assertFalse(self.window.tag_controller.admitted)

    def test_delete_intent_is_durable_before_worker_and_ack_before_refresh(self):
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.assertEqual(self.window.saved[0][QUEUE][0]['request'], self.request)
        self.assertFalse(self.applied)
        self.controller.timer.stop();self.controller.pump()
        self.window.tag_controller.deliver()
        self.assertEqual(self.applied, [self.request])
        self.assertEqual(self.window.saved[-1][QUEUE], [])
        self.assertEqual(self.window.published[0].source_tags, [])

    def test_all_three_durable_phase_clocks_are_privately_captured_before_admission(self):
        self.request['clocks'] = dict(target='2026-11-13 03:02:08.181 +00:00',
            siblings='2026-11-13 03:02:08.207 +00:00', associations='2026-11-13 03:02:08.083 +00:00')
        original = deepcopy(self.request)
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.request['clocks']['associations'] = self.request['timestamp']
        self.assertEqual(self.window.saved[0][QUEUE][0]['request'], original)
        self.assertEqual(self.controller.pending[0]['request'], original)
        self.controller.timer.stop();self.controller.pump()
        self.window.tag_controller.deliver()
        self.assertEqual(self.applied, [original])

    def test_assignment_and_rule_effects_do_not_borrow_a_silent_rule_rewrite(self):
        lib = self.window.lib
        lib.tracks_by_id['song'] = Track('song', 'Song', '', 'file:///synthetic.wav', source_tag_ids=[TAG.tag_id])
        lib.source_playlist_catalog['nodes'] = [dict(ID='123', Name='Smart', Attribute=4,
            rb_local_deleted=0, SmartList=smart_tag_rule('123', [TAG.tag_id]))]
        before = deepcopy(lib)
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.controller.timer.stop()
        self.assertEqual(lib, before)
        self.assertEqual(self.controller.pending[0]['request'], self.request)
        self.assertFalse(self.window.tag_controller.admitted)

    def test_failed_ack_preserves_exact_request_and_blocks_re_admission(self):
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.controller.timer.stop();self.controller.pump()
        self.window.save_ok = False
        self.window.tag_controller.deliver()
        self.assertEqual(self.controller.pending[0]['request'], self.request)
        self.assertTrue(self.controller.pending[0]['error'])
        self.assertFalse(self.window.published)
        self.controller.pump()
        self.assertEqual(len(self.window.tag_controller.admitted), 1)

    def test_last_tag_committed_before_restart_can_replay_when_fresh_library_is_empty(self):
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.controller.timer.stop()
        self.window.lib = replace(self.window.lib, source_tags=[])
        self.assertEqual(self.controller.deletion_reason(), '')
        self.controller.pump()
        self.window.tag_controller.deliver()
        self.assertEqual(self.controller.pending, [])
        self.assertEqual(self.applied, [self.request])

    def test_fresh_reader_still_showing_target_cannot_acknowledge_deletion(self):
        self.controller.loader = lambda _: self.window.lib
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.controller.timer.stop();self.controller.pump()
        self.window.tag_controller.deliver()
        self.assertTrue(self.controller.pending[0]['error'])
        self.assertFalse(self.window.published)

    def test_fresh_reader_retaining_target_assignment_cannot_acknowledge_deletion(self):
        self.window.lib.tracks_by_id['song'] = Track('song', 'Song', '', 'file:///synthetic.wav', source_tag_ids=[TAG.tag_id])
        self.assertTrue(self.controller.enqueue_deletion(self.request))
        self.controller.timer.stop();self.controller.pump()
        self.window.tag_controller.deliver()
        self.assertTrue(self.controller.pending[0]['error'])
        self.assertEqual(self.controller.pending[0]['request'], self.request)
        self.assertFalse(self.window.published)

    def context(self):
        lib = self.window.lib
        return str(lib.source), lib.source_kind, lib.source_library_id

    def test_clicked_tag_pins_same_named_category_and_leaf_uuids(self):
        second = replace(TAG, tag_id='42', source_uuid='second', category_id='2', category_uuid='category-two')
        self.window.lib = replace(self.window.lib, source_tags=[TAG, second])
        self.window.tag_definition_controller = self.controller
        with mock.patch('desktop.tag_creation.QMessageBox.question', return_value=QMessageBox.Yes):
            self.assertTrue(TagCreationMixin._delete_tag(self.window, second, self.context()))
        self.controller.timer.stop()
        request = self.controller.pending[0]['request']
        self.assertEqual((request['tag_id'], request['tag_uuid'], request['category_uuid']),
                         ('42', 'second', 'category-two'))

    def test_handler_asks_one_default_no_effects_confirmation_for_exact_clicked_tag(self):
        self.window.tag_definition_controller = self.controller
        with mock.patch('desktop.tag_creation.QMessageBox.question', return_value=QMessageBox.No) as confirm:
            self.assertFalse(TagCreationMixin._delete_tag(self.window, TAG, self.context()))
            self.assertFalse(self.window.saved)
            self.assertEqual(confirm.call_args.args[-1], QMessageBox.No)
            self.assertIn('Songs and audio files are preserved', confirm.call_args.args[2])
        with mock.patch('desktop.tag_creation.QMessageBox.question', return_value=QMessageBox.Yes):
            self.assertTrue(TagCreationMixin._delete_tag(self.window, TAG, self.context()))
        self.controller.timer.stop()
        self.assertEqual(self.controller.pending[0]['request']['tag_id'], TAG.tag_id)
        self.assertEqual(self.controller.pending[0]['request']['action'], 'delete')
        self.assertFalse(self.window.tag_controller.admitted)

    def test_context_source_change_or_target_change_during_confirmation_admits_nothing(self):
        self.window.tag_definition_controller = self.controller
        for change in ('source', 'tag'):
            with self.subTest(change=change):
                original = self.window.lib
                def changed(*_args):
                    self.window.lib = (replace(original, source='/different/master.db') if change == 'source'
                        else replace(original, source_tags=[replace(TAG, source_uuid='replaced')]))
                    return QMessageBox.Yes
                with mock.patch('desktop.tag_creation.QMessageBox.question', side_effect=changed):
                    self.assertFalse(TagCreationMixin._delete_tag(self.window, TAG, self.context()))
                self.window.lib = original
        with mock.patch('desktop.tag_creation.QMessageBox.question') as confirm:
            self.assertFalse(TagCreationMixin._delete_tag(self.window, TAG, ('/old/source', 'rekordbox-db', 'old')))
            confirm.assert_not_called()
        self.assertFalse(self.window.saved)
        self.assertFalse(self.window.tag_controller.admitted)


